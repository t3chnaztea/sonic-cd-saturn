#!/usr/bin/env python3
"""Extract Stardust Speedway COL7A-D palette scripts into src/background_r7_palette.inc.

    python3 tools/ss_palette_assets.py           write the include
    python3 tools/ss_palette_assets.py --check   fail if the include is stale

COL7A/COL7D clchgctr() walk local (index, count, (timer, color)[count]) scripts
with clchg_sub0(&pChgTime, &pChgCnt, cnt, col), one timer/frame slot per call;
COL7B/COL7C clchgctr() are empty.  Every script and color table must appear
byte-identical in each retail MMD that links it (R7<act><era>).
"""
import argparse
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tools'))
from convert_assets import palette  # noqa: E402
from extract_mmd import disc_files  # noqa: E402

SOURCE = ROOT/'build/audit/source/src/R7'
OUT = ROOT/'src/background_r7_palette.inc'
MMDS = {'A': ['R71A', 'R72A'], 'B': ['R71B', 'R72B'], 'C': ['R71C', 'R72C', 'R73C'], 'D': ['R71D', 'R72D', 'R73D']}
CALL = re.compile(r'clchg_sub0\(&pChgTime, &pChgCnt, (\w+), (\w+)\)')


def entries(body):
    v = list(map(int, re.findall(r'\d+', re.sub(r'/\*.*?\*/', '', body))))
    assert len(v) % 4 == 0 and all(x % 32 == 0 for i, x in enumerate(v) if i % 4 != 3)
    return b''.join(struct.pack('>H', v[i]//16 | v[i+1]//16 << 4 | v[i+2]//16 << 8) for i in range(0, len(v), 4))


def build():
    files = disc_files((ROOT/'build/retail/sonic.iso').read_bytes())
    out = ['/* Generated by tools/ss_palette_assets.py from COL7A-D.C, cross-checked in the retail MMDs.  Do not edit. */']
    sets, proofs = [], 0
    for letter in 'ABCD':
        src = (SOURCE/f'COL7{letter}.C').read_text()
        m = re.search(r'void clchgctr\(void\) \{(.*?)\n\}', src, re.S)
        if not m:
            assert re.search(r'void clchgctr\(void\) \{\}', src), letter
            sets.append('{0,{{0,0,0}}}')
            continue
        fn = m[1]
        # COL7D: the last call picks its script by act and shares one slot.  The
        # C reads `if (stageno.b.l) cnt1 else cnt`; retail CRAM shows R71D
        # animating cnt1's entry (58) and R72D/R73D cnt's (62), so retail runs
        # cnt1 in Act 1 and cnt in Acts 2/3 (tools/test_ss_palette.py).
        code = re.sub(r'/\*.*?\*/', '', fn)
        br = re.search(r'if \(stageno\.b\.l\) \{\s*clchg_sub0\(&pChgTime, &pChgCnt, (\w+), (\w+)\);.*?\} else \{\s*clchg_sub0\(&pChgTime, &pChgCnt, (\w+), (\w+)\);', code, re.S)
        calls = CALL.findall(code[:br.start()] if br else code)
        alt = None
        if br:
            assert br[2] == br[4]
            calls.append((br[1], br[2]))
            alt = br[3]
        names = []
        for n, (cnt, col) in enumerate(calls):
            table = bytes(int(v) & 255 for v in re.findall(r'-?\d+', re.sub(r'/\*.*?\*/', '', re.search(r'char '+cnt+r'\[\d+\] = \{(.*?)\};', fn, re.S)[1])))
            colors = entries(re.search(r'PALETTEENTRY '+col+r'\[\d+\] = \{(.*?)\};', fn, re.S)[1])
            assert len(table) == table[1]*2+2, cnt
            for mm in MMDS[letter]:
                mmd = files[mm+'__.MMD']
                assert table in mmd and colors in mmd, (mm, cnt, col)
                proofs += 2
            words = struct.unpack(f'>{len(colors)//2}H', palette(colors))
            out.append(f'static const uint8_t r7_{letter}{n}_script[{len(table)}] = {{{",".join(map(str, table))}}};')
            out.append(f'static const uint16_t r7_{letter}{n}_colors[{len(words)}] = {{{",".join(map(str, words))}}};')
            names.append(f'{{r7_{letter}{n}_script,r7_{letter}{n}_colors,0}}')
        if alt:
            table = bytes(int(v) & 255 for v in re.findall(r'-?\d+', re.sub(r'/\*.*?\*/', '', re.search(r'char '+alt+r'\[\d+\] = \{(.*?)\};', fn, re.S)[1])))
            assert len(table) == table[1]*2+2 and all(table in files[mm+'__.MMD'] for mm in MMDS[letter]), alt
            proofs += 1
            out.append(f'static const uint8_t r7_{letter}_alt_script[{len(table)}] = {{{",".join(map(str, table))}}};')
            names[-1] = names[-1][:-3]+f',r7_{letter}_alt_script}}'
        assert len(names) <= 8
        sets.append(f'{{{len(names)},{{{",".join(names)}}}}}')
    out.append('typedef struct { const uint8_t *script; const uint16_t *colors; const uint8_t *act23; } r7_pal_call;  /* act23: script in acts 2/3 */')
    out.append('typedef struct { uint8_t calls; r7_pal_call call[8]; } r7_pal_set;')
    out.append('static const r7_pal_set r7_pal_sets[4] = {'+','.join(sets)+'};')
    return '\n'.join(out)+'\n', proofs


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    text, proofs = build()
    if args.check:
        if OUT.read_text() != text:
            sys.exit(f'FAIL: {OUT.relative_to(ROOT)} is stale')
        print(f'PASS: {OUT.relative_to(ROOT)} current; {proofs} script/color tables found in retail MMDs')
        return
    OUT.write_text(text)
    print('wrote', OUT.relative_to(ROOT), f'({proofs} retail table matches)')


if __name__ == '__main__':
    main()

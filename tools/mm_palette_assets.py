#!/usr/bin/env python3
"""Extract Metallic Madness COL8A-D palette scripts into src/background_r8_palette.inc.

    python3 tools/mm_palette_assets.py           write the include
    python3 tools/mm_palette_assets.py --check   fail if the include is stale

Each COL8x.C clchgctr() -> colchg8x() runs clchg_sub0(&clchgtim[i], &clchgcnt[i],
col8a<k>cnt, col8a<k>col): slots 0-2 always, slots 3-5 by act (stageno.b.l).
The per-act script lists below are read from the C text (asserted verbatim) and
proven against retail CRAM for every program by tools/test_mm_palette.py.
Every table must appear byte-identical in each retail MMD that links it.
"""
import argparse
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tools'))
from convert_assets import palette  # noqa: E402
from extract_mmd import disc_files  # noqa: E402
from tt_palette_assets import entries  # noqa: E402

SOURCE = ROOT/'build/audit/source/src/R8'
OUT = ROOT/'src/background_r8_palette.inc'
MMDS = {'A': ['R81A', 'R82A'], 'B': ['R81B', 'R82B'], 'C': ['R81C', 'R82C', 'R83C'], 'D': ['R81D', 'R82D', 'R83D']}
# scripts per act (1, 2, 3) after the shared col8a0-2, and the C statement that decides it
ACTS = {
    'A': (['3', '4', '5'], ['6', '7', '8'], ['3', '4', '5'], 'if (stageno.b.l != 1) {'),
    'B': (['3', '4'], ['5', '6'], ['3', '4'], 'if (stageno.b.l != 1) {'),
    'C': (['3'], [], [], 'if (stageno.b.l == 0) {'),
    # COL8D: the C tests stageno.b.h + 1 == 1 (never true in zone 8) for the
    # Act 2 set; retail CRAM shows Act 2 running col8a6-8 and Act 3 col8a9-b,
    # so retail's test is on the act (tools/test_mm_palette.py).
    'D': (['3', '4', '5'], ['6', '7', '8'], ['9', 'a', 'b'], 'if (stageno.b.h + 1 == 1) {'),
}


def build():
    files = disc_files((ROOT/'build/retail/sonic.iso').read_bytes())
    out = ['/* Generated by tools/mm_palette_assets.py from COL8A-D.C, cross-checked in the retail MMDs.  Do not edit. */']
    sets, proofs = [], 0
    for letter in 'ABCD':
        src = (SOURCE/f'COL8{letter}.C').read_text()
        body = re.sub(r'/\*.*?\*/', '', re.search(r'void colchg8'+letter.lower()+r'\(void\) \{(.*?)\n\}', src, re.S)[1])
        assert ACTS[letter][3] in ' '.join(body.split()), letter
        used = sorted({k for act in ACTS[letter][:3] for k in act} | {'0', '1', '2'})
        for k in used:
            cnt, col = f'col8a{k}cnt', f'col8a{k}col'
            assert f'&clchgcnt' in body and cnt in body, (letter, cnt)
            table = bytes(int(v) & 255 for v in re.findall(r'-?\d+', re.sub(r'/\*.*?\*/', '', re.search(r'char '+cnt+r'\[\d+\] = \{(.*?)\};', src, re.S)[1])))
            colors = entries(src, col)
            if len(table) == table[1]*2+1:
                # COL8C col8a3cnt is one byte short: clchg_sub0 reads the byte after
                # it; take that byte from the retail MMDs (it must agree)
                nxt = {files[mm+'__.MMD'][files[mm+'__.MMD'].index(table)+len(table)] for mm in MMDS[letter]}
                assert len(nxt) == 1, (letter, cnt, nxt)
                table += bytes(nxt)
            assert len(table) == table[1]*2+2, cnt
            need = max(table[3::2])+1
            if need > len(colors)//2:
                # COL8C col8a3: the short table's pairs name colors 22 and 66 of a
                # 3-entry table; retail reads the words that follow it in the MMD
                # (retail CRAM confirms).  They must agree across the MMDs.
                ext = {files[mm+'__.MMD'][files[mm+'__.MMD'].index(colors):][:need*2] for mm in MMDS[letter]}
                assert len(ext) == 1, (letter, cnt)
                colors = ext.pop()
            for mm in MMDS[letter]:
                assert table in files[mm+'__.MMD'] and colors in files[mm+'__.MMD'], (mm, cnt)
                proofs += 2
            words = struct.unpack(f'>{len(colors)//2}H', palette(colors))
            out.append(f'static const uint8_t r8_{letter}{k}_script[{len(table)}] = {{{",".join(map(str, table))}}};')
            out.append(f'static const uint16_t r8_{letter}{k}_colors[{len(words)}] = {{{",".join(map(str, words))}}};')
        acts = []
        for act in ACTS[letter][:3]:
            calls = ['0', '1', '2']+act
            acts.append(f'{{{len(calls)},{{{",".join(f"{{r8_{letter}{k}_script,r8_{letter}{k}_colors}}" for k in calls)}}}}}')
        sets.append('{'+','.join(acts)+'}')
    out.append('typedef struct { const uint8_t *script; const uint16_t *colors; } r8_pal_call;')
    out.append('typedef struct { uint8_t calls; r8_pal_call call[6]; } r8_pal_set;')
    out.append('static const r8_pal_set r8_pal_sets[4][3] = {'+','.join(sets)+'};  /* [era][act] */')
    return '\n'.join(out)+'\n', proofs


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    text, proofs = build()
    if args.check:
        if OUT.read_text() != text:
            sys.exit(f'FAIL: {OUT.relative_to(ROOT)} is stale')
        print(f'PASS: {OUT.relative_to(ROOT)} current; {proofs} script/color tables found in retail MMDs')
        return
    OUT.write_text(text)
    print('wrote', OUT.relative_to(ROOT), f'({proofs} retail table matches)')


if __name__ == '__main__':
    main()

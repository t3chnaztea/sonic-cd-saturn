#!/usr/bin/env python3
"""Compile checked Tidal Tempest scroll IR (tools/scroll/R4/ir) into src/background_r4_tables.inc.

    python3 tools/background_r4_assets.py            write the include
    python3 tools/background_r4_assets.py --check    fail if the include is stale

Program ids are act*4+era (0-3 SCR41A-D, 4-7 SCR42A-D, 10-11 SCR43C-D).
SCR42B/SCR42D have no C source; they take the SCR42A/SCR42C documents (both
are the same one-layer program) and tools/test_r4_scroll.py proves that
against 68 retail CPU captures of R42B/R42D each.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IR = ROOT/'tools/scroll/R4/ir'
OUT = ROOT/'src/background_r4_tables.inc'
SOURCE = ROOT/'build/audit/source/src/R4'
PROGRAMS = {0: 'SCR41A', 1: 'SCR41B', 2: 'SCR41C', 3: 'SCR41D', 4: 'SCR42A', 5: 'SCR42A', 6: 'SCR42C',
            7: 'SCR42C', 10: 'SCR43C', 11: 'SCR43D'}
LAYERS = ['camera', 'scrb_h_posit', 'scrc_h_posit', 'scrz_h_posit']


def row_code(expr):
    """{op, layer, k, D, m}: op 1 layer, 2 interp(layer -> camera)."""
    if expr['op'] == 'layer':
        return (1, LAYERS.index(expr['layer']), 0, 1, 0)
    assert expr['op'] == 'interp' and expr['to'] == 'camera' and expr['diff_bits'] == 32, expr
    return (2, LAYERS.index(expr['from']), expr['k'], expr['D'], expr['m'])


def wrttbl(name):
    text = (SOURCE/f'{name}.C').read_text()
    used = 'z81awrttbl[wD0 + 1]' in text
    match = re.search(r'z81awrttbl\[129\]\s*=\s*\{(.*?)\}', text, re.S)
    values = [int(v) for v in re.findall(r'-?\d+', re.sub(r'/\*.*?\*/', '', match.group(1)))]
    assert len(values) == 129
    # Programs whose scrollwrtb never reads the table draw every row from scrb.
    return values if used else [2]*129


def build():
    lines = ['/* Generated by tools/background_r4_assets.py from tools/scroll/R4/ir.  Do not edit. */']
    sine = None
    rows, meta, tables = [], [], []
    for pid in range(12):
        name = PROGRAMS.get(pid)
        if not name:
            meta.append('{0}')
            continue
        doc = json.loads((IR/f'{name}.json').read_text())
        assert doc['ir'] == 'scroll-ir/1+r4' and not doc['bands'] and all(c['rule'] == 'CLAMP0' for c in doc['corrections']), name
        entries = []
        for run in doc['runs']:
            entries += [row_code(run['expr'])]*run['entries']
        # zonescrsetsub0 walks on past the buffer mask into rows scroll() also
        # wrote (SCR42/43: 192 written, 128 addressed); the IR counts them.
        past = doc['rules']['rows_past_buffer']//1
        if past:
            assert len(doc['runs']) == 1, name
            entries += [entries[-1]]*past
        mask = doc['buffer_lines']//8-1
        water = doc['water']
        assert water['sign'] == -1 and water['phase'] == {'word': 'waterdirec', 'step': 128}
        sine = sine or water['table']
        assert water['table'] == sine
        g = doc['bg_y']
        bgy = 1 if g['op'] == 'pieces' else 0
        assert bgy or g == {'op': 'rate', 'C': 128}, g
        body = ','.join('{%d,%d,%d,%d,%d}' % e for e in entries)
        rows.append(f'static const r4_row r4_rows_{pid}[{len(entries)}] = {{{body}}};  /* {name}.C */')
        tables.append(wrttbl(name))
        meta.append(f'{{"{name}",{len(entries)},{mask},{bgy},r4_rows_{pid},r4_wrttbl_{pid}}}')
        rows.append(f'static const uint8_t r4_wrttbl_{pid}[129] = {{{",".join(map(str, tables[-1]))}}};')
    lines += rows
    lines.append(f'static const int8_t r4_awasintbl[256] = {{{",".join(map(str, sine))}}};  /* TBL0.C */')
    lines.append(f'static const r4_program r4_programs[12] = {{{",".join(meta)}}};')
    return '\n'.join(lines)+'\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    text = build()
    if args.check:
        if OUT.read_text() != text:
            sys.exit(f'FAIL: {OUT.relative_to(ROOT)} is stale; run tools/background_r4_assets.py')
        print(f'PASS: {OUT.relative_to(ROOT)} matches tools/scroll/R4/ir')
        return
    OUT.write_text(text)
    print('wrote', OUT.relative_to(ROOT))


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Generate the Act 3 boss (BOSS_1.C) and the touch response it needs (COLI1.C pcol).

Saturn/host build (build/probe-source/boss_1.c): every PC scratch cast such as
((short*)p)[26] becomes a little-endian byte accessor at the same PC offset
(actfree for offsets 46-67, xspeed/yspeed for 16-19). The PS2 actor is
little-endian, so the SH-2 and the host both read the values the PC code reads.
Desktop reference (build/player-reference/boss_1.c): the original casts on the
68-byte PC actor layout; tools/test-boss.sh runs both and compares them.
Only includes, the boss sprite pattern tokens (reference) and the player hurt
path (pcole calls the native hurt frontend) are changed.
"""
import re
from audit_source import ROOT, UPSTREAM
from generated_io import write_text

NATIVE = ROOT / 'build/probe-source'
REFERENCE = ROOT / 'build/player-reference'
TYPES = {'short': 'int16_t', 'unsigned short': 'uint16_t', 'int': 'int32_t', 'char': 'int8_t', 'unsigned char': 'uint8_t'}
SIZES = {'int16_t': 2, 'uint16_t': 2, 'int32_t': 4, 'int8_t': 1, 'uint8_t': 1}
HEAD = re.compile(r'\(\((unsigned short|short|int|unsigned char|char)\*\)')


def functions(source):
    source = re.sub(r'/\*.*?\*/', '', source, flags=re.S)
    result = {}
    for match in re.finditer(r'^(?:unsigned |static )*(?:void|char|short|int)\s+(\w+)\([^;]*?\)\s*\{', source, re.M):
        end, depth = match.end(), 1
        while depth:
            depth += (source[end] == '{') - (source[end] == '}')
            end += 1
        result[match[1]] = source[match.start():end]
    return result


def data_names(text):
    """File-scope initialized data the generated file defines (tables, patterns)."""
    s = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    names, depth, buf = [], 0, ''
    for ch in s:
        if ch == '{':
            depth += 1
        elif ch == '}':
            depth -= 1
        if depth == 0:
            buf += ch
            if ch in ';}':
                st, buf = buf.strip(), ''
                if '=' in st and not st.startswith(('#', 'typedef')):
                    head = st.split('=')[0]
                    if '(' in head and not re.search(r'\(\s*\*', head):
                        continue
                    m = re.search(r'([A-Za-z_]\w*)\s*(\[[^\]]*\]\s*)*$', head.strip())
                    if m:
                        names.append(m[1])
    return names


def overlay_data(native, moved, text):
    """Initialized data of `native` that only overlay code reaches: no function of `text`
    outside `moved` and no resident source (src/, e.g. src/boss.c ARM3_SECOND) names it,
    and no such datum's initializer points at it."""
    data = set(data_names(native))
    named = set()
    for path in (ROOT / 'src').glob('*.[chi]*'):
        named |= set(re.findall(r'\w+', path.read_text(encoding='latin1'))) & data
    inits = {}
    for st in re.sub(r'/\*.*?\*/', '', native, flags=re.S).split(';'):
        if '=' in st:
            for n in data_names(st + ';'):
                inits[n] = st.split('=', 1)[1]
    keep = set(named)
    for name, body in functions(text).items():
        if name not in moved:
            keep |= set(re.findall(r'\w+', body)) & data
    todo = list(keep)
    while todo:
        for n in set(re.findall(r'\w+', inits.get(todo.pop(), ''))) & data - keep:
            keep.add(n)
            todo.append(n)
    return sorted(data - keep)


def zone_header(zone, boss, renamed, native, resident=(), text=None):
    """<BOSS>_ZONE.H: in the Saturn build (SCD_ZONE_OVERLAY) every function the generated
    boss file defines gets its zone prefix, which places it in that zone's code overlay
    (src/saturn.x, heap plan B). src/boss.c then reaches it only through the zone's
    scd_boss_zone_ops (src/boss_zone.h); tools/test_zone_code.py audits the link.
    `resident` names stay resident: the RIDECHK.C copies are the same in every boss.
    With `text` (the whole generated file), initialized data only overlay code reaches
    joins the overlay too (src/saturn.x .data.r<n>_b<n>_*, .rodata.r<n>_*): the overlay
    reloads with the zone, as the original program does."""
    moved = {n for n in functions(native) if n not in resident}
    names = sorted(f'{boss}_{n}' if n in renamed else n for n in moved)
    script = 'prepare_boss.py' if boss == 'boss1' else f'prepare_boss_r{boss[4:]}.py'
    tag = f'r{zone[1:]}_b{zone[1:]}_'
    data = [] if text is None else [f'{boss}_{n}' if n in renamed else n
                                    for n in overlay_data(native, moved, text) if not n.startswith(f'r{zone[1:]}_')]
    return (f'/* Generated by tools/{script}: {boss} code in the R{zone[1:]} overlay. */\n'
            '#ifdef SCD_ZONE_OVERLAY\n' + ''.join(f'#define {n} {zone}_{n}\n' for n in names)
            + ''.join(f'#define {n} {tag}{n}\n' for n in data) + '#endif\n')


def closing(text, at):
    depth = 0
    for i in range(at, len(text)):
        depth += (text[i] in '([') - (text[i] in ')]')
        if not depth:
            return i
    raise ValueError('unbalanced expression')


def adapt(text):
    """Rewrite PC scratch casts into SCD_GET/SCD_SET little-endian accessors."""
    out, i = [], 0
    while (m := HEAD.search(text, i)):
        end = closing(text, m.start())
        index = re.match(r'\[(\d+)\]', text[end + 1:])
        if not index:
            raise ValueError(f'cast without index: {text[m.start():end + 8]}')
        kind = TYPES[m[1]]
        offset = int(index[1]) * SIZES[kind]
        if not (46 <= offset and offset + SIZES[kind] <= 68 or 16 <= offset and offset + SIZES[kind] <= 20):
            raise ValueError(f'PC offset {offset} outside actfree and xspeed/yspeed')
        actor = adapt(text[m.end():end])
        after = end + 1 + index.end()
        assign = re.match(r'\s*(=(?!=)|\+=|-=)', text[after:])
        if assign:
            start = after + assign.end()
            stop, depth = start, 0
            while text[stop] != ';' or depth:
                depth += (text[stop] in '([') - (text[stop] in ')]')
                stop += 1
            value = adapt(text[start:stop])
            if assign[1] != '=':
                value = f'SCD_GET({kind}, {actor}, {offset}) {assign[1][0]} ({value})'
            out.append(text[i:m.start()] + f'SCD_SET({kind}, {actor}, {offset}, {value})')
            i = stop
        else:
            out.append(text[i:m.start()] + f'SCD_GET({kind}, {actor}, {offset})')
            i = after
    out.append(text[i:])
    return ''.join(out)


ACCESSORS = '''#include <stddef.h>
#include <stdint.h>
/* PC actor bytes 16-19 are xspeed/yspeed and 46-67 actfree; words are little-endian. */
_Static_assert(offsetof(sprite_status, yspeed) == offsetof(sprite_status, xspeed) + 2, "speed words");
static inline uint8_t *scd_pc_bytes(sprite_status *p, unsigned offset) {
    return offset >= 46 ? p->actfree + (offset - 46) : (uint8_t *)&p->xspeed + (offset - 16);
}
static inline uint32_t scd_pc_get(sprite_status *p, unsigned offset, unsigned size) {
    const uint8_t *b = scd_pc_bytes(p, offset); uint32_t v = 0;
    for (unsigned n = size; n--;) v = v << 8 | b[n];
    return v;
}
static inline void scd_pc_set(sprite_status *p, unsigned offset, unsigned size, uint32_t v) {
    uint8_t *b = scd_pc_bytes(p, offset);
    for (unsigned n = 0; n < size; n++, v >>= 8) b[n] = v;
}
#define SCD_GET(type, p, offset) ((type)scd_pc_get((p), (offset), sizeof(type)))
#define SCD_SET(type, p, offset, value) scd_pc_set((p), (offset), sizeof(type), (uint32_t)(type)(value))
'''
# pcol is named scd_pcol_r1: src/boss.c's pcol picks the running round's COLI.
PRELUDE = '''#define pcol scd_pcol_r1
#include "EQU.H"
#include "BOSS_1.H"
#include "COLI1.H"
#include "ACTION.H"
#include "ACTSET.H"
#include "DIRCOL.H"
#include "ETC.H"
#include "FCOL.H"
#include "GOAL.H"
#include "LOADER2.H"
#include "PLAYSUB.H"
#include "SCORE.H"
extern void colorset2(int ColorNo);
extern void divdevset(int);
extern void soundset(short);
extern void scd_objects_hurt(int source_x);
'''
# COLI1.C pcol and the touch classes the boss colino values reach (60-63, 0x80).
COLI = ['pcol', 'CollitblDataXchk', 'CollitblDataYchk', 'ColliHitChk', 'pcolitem', 'pcolnomal',
        'pcolplay2', 'pcolplay', 'pcolspecial', 'eggman_chk', 'yago', 'main_attack']
PCOLE = '''short pcole(sprite_status* pActwk, sprite_status* pColliAct) {
  if (((unsigned short*)pActwk)[26] != 0)
    return -1;
  /* playdamageset: the native hurt frontend drops rings, shield or a life. */
  scd_objects_hurt(pColliAct->xposi.w.h);
  return -1;
}
'''

# ACT13C.C act_tbl[actno-1] for BOSS_1.C's actors (42-50). src/boss.c reaches round 1's
# boss code only through r1_boss_zone_ops (src/boss_zone.h), as it does rounds 3-5.
ROUND1 = '''#include "boss_zone.h"
static void (*z1_boss_routine(unsigned id))(sprite_status *){
  static void (*const routines[9])(sprite_status *)={egg1,egg1body,egg1leg1,egg1leg2,egg1leg3,egg1arm1,egg1arm2,egg1arm3,egg1arm4};
  return id>=42 && id<=50?routines[id-42]:0;
}
const scd_boss_zone_ops r1_boss_zone_ops={.routine=z1_boss_routine,.pcol=pcol};
'''


def main():
    boss = (UPSTREAM / 'src/R1/BOSS_1.C').read_text(encoding='latin1')
    boss = re.sub(r'#include "[^"]*"\n', '', boss)
    # egg1arm3_01 falls off its end when bit 7 of actfree[2] is set; the caller only
    # tests the result for drawing. Both builds return 1 there, as every other path does.
    tail = '    return 1; /* Line 2420, Address: 0x102e020 */\n  }\n} /* Line 2422, Address: 0x102e024 */'
    if boss.count(tail) != 1:
        raise ValueError('egg1arm3_01 changed')
    boss = boss.replace(tail, tail[:-len('} /* Line 2422, Address: 0x102e024 */')] + '  return 1;\n} /* Line 2422, Address: 0x102e024 */')
    # egg1arm2_set and egg1leg1_set scale the sine/cosine with C division (toward
    # zero); retail asr.w #4 rounds down (R13C $20CB80/$20D134, R13D $20CB98/$20D14C):
    # leg angle 88 gives cos -142, an x offset of -9, not -8.
    for name in ('egg1arm2_set', 'egg1leg1_set'):
        i = boss.index(f'void {name}('); j = boss.index('\n}', i); body = boss[i:j]
        assert body.count('sinl.w.l /= 16;') == 1 and body.count('cosl.w.l /= 16;') == 1, name
        boss = boss[:i] + body.replace('sinl.w.l /= 16;', 'sinl.w.l >>= 4;').replace('cosl.w.l /= 16;', 'cosl.w.l >>= 4;') + boss[j:]
    # egg1arm2 angle steps compare unsigned in retail: R13C $20CABE subq.b #2 + bhi
    # (old angle above 2) and $20CADE cmpi.b #48 + bcs, so 126 + 2 = 128 snaps to 48
    # (PPZ3C update 1026); the PC signed char wraps through -128 instead. Its fall
    # (egg1arm2_05) tests the Y word, cmpi.w #576,$C(a0) at $20CB4C; the PC compares
    # the whole 16.16 long and deletes the arm on its first falling update.
    for old, new in (('  ((char*)pActwk)[46] -= 2; /* Line 2258, Address: 0x102d97c */\n'
                      '  if (((char*)pActwk)[46] > 0)',
                      '  ((char*)pActwk)[46] -= 2; /* Line 2258, Address: 0x102d97c */\n'
                      '  if ((unsigned char)(((char*)pActwk)[46] + 2) > 2)'),
                     ('if (((char*)pActwk)[46] < 48) /* Line 2276,', 'if ((unsigned char)((char*)pActwk)[46] < 48) /* Line 2276,'),
                     ('if (pActwk->yposi.l >= 576) /* Line 2325,', 'if (pActwk->yposi.w.h >= 576) /* Line 2325,'),
                     # egg1leg3_03 lands when the Y offset's integer word reaches 0:
                     # retail cmpi.w #0,$38(a0) + bgt (R13C $20D58C); the PC tests the
                     # whole long, one update later when a fraction remains (PPZ3C 1209).
                     ('if (((int*)pActwk)[15] <= 0) /* Line 3470,', 'if (((short*)pActwk)[31] <= 0) /* Line 3470,')):
        assert boss.count(old) == 1, old
        boss = boss.replace(old, new)
    # Retail spd_up (R13C $20C4F2) restores a1 from the stack before its last part,
    # which walks a1/a2 through the arms: on its first update egg1body_06 ($20C780)
    # tests the leg flags through a1 = arm.$30.$30.$30 and a2 = egg1.$32 (arm1), so
    # the step starts an update later (PPZ3C 1804). A null link reads ROM in retail;
    # it is treated as a failed test here.
    old = '    spd_up(pActwk); /* Line 1990, Address: 0x102cacc */\n'
    assert boss.count(old) == 1, old
    boss = boss.replace(old, old +
        '    subact2 = ((short*)&actwk[((short*)pActwk)[25]])[27];\n'
        '    subact1 = subact2 ? ((short*)&actwk[subact2])[26] : 0;\n'
        '    if (subact1) subact1 = ((short*)&actwk[((short*)&actwk[subact1])[26]])[26];\n'
        '    if (!subact1 || !subact2) return 1;\n')
    coli_source = (UPSTREAM / 'src/R1/COLI1.C').read_text(encoding='latin1')
    tables = coli_source[coli_source.index('unsigned short escoretbl'):coli_source.index('#ifdef R11A')]
    coli = functions(coli_source)
    patchg = functions((UPSTREAM / 'src/PLAYSUB.C').read_text(encoding='latin1'))['patchg']
    body = boss + '\n' + tables + 'static unsigned char bCarry;\n' + '\n'.join([PCOLE] + [coli[n] for n in COLI]) + '\n' + patchg + '\n'
    header = (UPSTREAM / 'src/R1/BOSS_1.H').read_text(encoding='latin1')
    # Read-only tables declared inside their functions are copied onto the
    # stack on every call at -Os. Give them static storage; every use is a read.
    for declaration in ('short egg1acttbl[20]', 'short bom_tbl[20]'):
        if body.count(declaration) != 1:
            raise ValueError(f'BOSS_1.C: {declaration} changed upstream')
        body = body.replace(declaration, 'static const ' + declaration)
    native = adapt(body)
    if HEAD.search(native):
        raise ValueError('unadapted PC cast')
    # COLI1.C (pcol runs in every zone without a boss of its own) and PLAYSUB.C patchg
    # stay resident; BOSS_1.C runs from the R1 overlay (heap plan B).
    zone = zone_header('z1', 'boss1', set(), native, COLI + ['pcole', 'patchg'], PRELUDE + ACCESSORS + native + ROUND1)
    for target in (NATIVE, REFERENCE):
        write_text(target / 'COLI1.H',(UPSTREAM / 'src/R1/COLI1.H').read_text(encoding='latin1'))
        write_text(target / 'BOSS1_ZONE.H',zone)
    write_text(NATIVE / 'BOSS_1.H',header)
    write_text(NATIVE / 'boss_1.c','#include "BOSS1_ZONE.H"\n' + PRELUDE + ACCESSORS + native + ROUND1)
    # Reference: original casts; the actor pattern pointer is a 32-bit token there.
    patterns = sorted(set(re.findall(r'->patbase = (\w+);', body)))
    tokens = ''.join(f'#define SCD_PATTERN_{name} {n + 1}u\n' for n, name in enumerate(patterns))
    reference = re.sub(r'->patbase = (\w+);', r'->patbase = SCD_PATTERN_\1;', body)
    write_text(REFERENCE / 'BOSS_1.H',header)
    write_text(REFERENCE / 'BOSS_PATTERNS.H',tokens)
    write_text(REFERENCE / 'boss_1.c','#include "BOSS1_ZONE.H"\n' + PRELUDE + '#include "BOSS_PATTERNS.H"\n' + reference + ROUND1)
    carry = functions((UPSTREAM / 'src/FCOL.C').read_text(encoding='latin1'))
    write_text(REFERENCE / 'carry.c',carry['CCset'] + '\n' + carry['CSset'] + '\n')
    print(f'Boss sources: BOSS_1.C, {len(COLI) + 1} COLI1.C touch functions and patchg; {len(HEAD.findall(body))} PC casts adapted')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Write patched COPIES of src/background.c under tools/scroll/port/.

src/background.c itself is never modified.  Each patch replaces one exact
text anchor that must occur exactly once; a missing or repeated anchor is a
failure, so a change to the port cannot silently skip a patch.

  background_wrap.c        the era 1/2/3 branch wraps background Y at 512
                           lines, as SCR11B/C/D do with (scrb_v_posit.w.h & 504)
  background_wrap_floor.c  the wrap, plus the era 0 ramps rounding down the
                           way SCR11A's 16.16 accumulator does (the port's C
                           division truncates toward zero)
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SRC = REPO / 'src/background.c'
OUT = HERE / 'port'

WRAP = [('    unsigned cloud_end=',
         '    y&=511; /* tools/scroll: SCR11B/C/D read the table at (scrb_v_posit.w.h & 504) */\n'
         '    unsigned cloud_end=')]
FLOOR = [
    ('#include "background.inc"\n',
     '#include "background.inc"\n'
     '/* tools/scroll: a 16.16 accumulator stepped per line rounds down */\n'
     'static int scroll_floor256(int v){return v>=0?v/256:-((-v+255)/256);}\n'),
    ('bush+((x-bush)*256/224)*(y-640)/256', 'bush+scroll_floor256(((x-bush)*256/224)*(y-640))'),
    ('bush+((x-bush)*256/224)*(y-1920)/256', 'bush+scroll_floor256(((x-bush)*256/224)*(y-1920))'),
]


def apply(text, patches):
    for old, new in patches:
        n = text.count(old)
        if n != 1:
            raise SystemExit(f'patch_port.py: anchor {old!r} occurs {n} times in {SRC}, expected 1')
        text = text.replace(old, new)
    return text


def main():
    src = SRC.read_text()
    OUT.mkdir(exist_ok=True)
    head = f'/* GENERATED by tools/scroll/patch_port.py from src/background.c. Do not edit. */\n'
    for name, patches in (('background_wrap.c', WRAP), ('background_wrap_floor.c', WRAP + FLOOR)):
        (OUT / name).write_text(head + apply(src, patches))
        print(f'wrote {(OUT / name).relative_to(REPO)}')


if __name__ == '__main__':
    main()

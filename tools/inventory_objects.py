#!/usr/bin/env python3
"""Inventory original PPZ1 records using each era's actual dispatch table."""
import collections,json,re,struct
from convert_assets import ROOT,DATA
from convert_objects import SUPPORTED
ppz=DATA/'Palmtree Panic';names={}
for era in ['Present','Past','Good Future','Bad Future']:
    names[era]={int(i,16):{'routine':routine,'name':name.strip()} for routine,i,name in re.findall(r'dc\.l\s+(\w+)\s*;\s*([0-9A-F]{2})\s*-\s*(.*)',(ppz/f'Object Index (Act 1 {era}).asm').read_text())}
records=[]
for x,y,kind,sub,eras,secondary in struct.iter_unpack('>HHBBBB',(ppz/'Data/Objects (Act 1).bin').read_bytes()):
    if x==65535:break
    kind&=127
    records.append({'x':x,'y':y&4095,'id':kind,'subtype':sub,'flags':y>>14,'era_bits':eras>>5,'secondary':secondary})
rows=[]
for kind in sorted({r['id'] for r in records}):
    rec=[r for r in records if r['id']==kind]
    rows.append({'id':kind,'source':names['Present'][kind], 'records':len(rec),'subtypes':sorted({r['subtype'] for r in rec}),'era_counts':{era:sum(bool(r['era_bits']&(1<<bit)) for r in rec) for era,bit in [('Present',1),('Past',0),('Good Future',2),('Bad Future',2)]},'runtime_imported':kind in SUPPORTED,'imported_records':sum(kind in SUPPORTED and (kind!=25 or r['subtype'] in (0,1,2,3,4,8,9)) for r in rec),'era_dispatch':{era:names[era][kind]['routine'] for era in names}})
for r in rows:r['active_names']=list(dict.fromkeys(names[era][r['id']]['name'] for era,count in r['era_counts'].items() if count))
report={'source':'sources.lock.json scddisasm','rows':rows,'records':records}
(ROOT/'build/object-coverage.json').write_text(json.dumps(report,indent=2)+'\n')
lines=['# PPZ1 original object coverage','','Generated by `tools/inventory_objects.py`. Imported does not mean behavior-complete. Counts are raw records; runtime ring groups expand. Good-future enemy suppression is a behavior rule separate from placement flags. Object labels use dispatch names from eras with actual placements.','','| ID | Object | Records | Subtypes | Imported |','| --- | --- | --- | --- | --- |']
for r in rows:lines.append(f"| {r['id']:02X} | {' / '.join(r['active_names'])} | {r['records']} | {', '.join(map(str,r['subtypes']))} | {str(r['imported_records'])+'/'+str(r['records'])} |")
(ROOT/'OBJECT-COVERAGE.md').write_text('\n'.join(lines)+'\n')
print(f'{len(records)} records, {len(rows)} IDs inventoried')

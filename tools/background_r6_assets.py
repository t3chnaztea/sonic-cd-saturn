#!/usr/bin/env python3
"""Compile the Wacky Workbench scroll IR (tools/scroll/R6/draft) into src/background_r6_tables.inc.

    python3 tools/background_r6_assets.py            write the include
    python3 tools/background_r6_assets.py --check    fail if the include is stale

Program ids are act*4+era (0-3 SCR61A-D, 4-7 SCR62A-D, 10-11 SCR63C-D).  Each
row is one hscrollwork entry scroll() writes (op 1 layer, 2 lerp, 3 step); the
plane rows come from each program's own z81awrttbl[49] (0 static, 2/4/6
scrb/scrc/scrz).  tools/test_r6_scroll.py checks the result against the
compiled original scroll() and retail CPU captures.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IR = ROOT/'tools/scroll/R6/draft'   # tools/scroll/R6/extract.py --round 6 --write
OUT = ROOT/'src/background_r6_tables.inc'
SOURCE = ROOT/'build/audit/source/src/R6'
PROGRAMS = {0: 'SCR61A', 1: 'SCR61B', 2: 'SCR61C', 3: 'SCR61D', 4: 'SCR62A', 5: 'SCR62B', 6: 'SCR62C',
            7: 'SCR62D', 10: 'SCR63C', 11: 'SCR63D'}
LAYERS = ['camera', 'scrb_h_posit', 'scrc_h_posit', 'scrz_h_posit']


def row_code(e):
    """{op, from, k, p, m, frac}"""
    if e['op'] == 'layer':
        return (1, LAYERS.index(e['layer']), 0, 0, 0, 0)
    assert e['to'] == 'camera', e
    if e['op'] == 'lerp':
        # p = product width: 16 narrows w*(camera - from) to an unsigned word
        assert e['prod_bits'] in (16, 32) and e['shift'] == 8, e
        return (2, LAYERS.index(e['from']), e['w'], e['prod_bits'], 0, 0)
    assert e['op'] == 'step', e
    return (3, LAYERS.index(e['from']), e['D'], e['num'], e['m'], e['frac'])


def wrttbl(name):
    text = (SOURCE/f'{name}.C').read_text()
    match = re.search(r'z81awrttbl\[49\]\s*=\s*\{(.*?)\}', text, re.S)
    values = [int(v) for v in re.findall(r'-?\d+', re.sub(r'/\*.*?\*/', '', match.group(1)))]
    assert len(values) == 49 and set(values) <= {0, 2, 4, 6}, name
    return values


def build():
    lines = ['/* Generated by tools/background_r6_assets.py from tools/scroll/R6/draft.  Do not edit. */']
    meta = []
    for pid in range(12):
        name = PROGRAMS.get(pid)
        if not name:
            meta.append('{0}')
            continue
        doc = json.loads((IR/f'{name}.json').read_text())
        assert doc['buffer_lines'] == 1024 and not doc['bands'], name
        assert doc['bg_y'] == {'op': 'shift', 'shifts': [2]}, name
        assert doc['layers'] == {'scrb_h_posit': {'C': 48, 'U': 0}, 'scrc_h_posit': {'C': 128, 'U': 0},
                                 'scrz_h_posit': {'C': 64, 'U': 0}}, name
        entries = []
        for run in doc['runs']:
            entries += [row_code(run['expr'])]*run['entries']
        assert len(entries)*8 == doc['table_end'], name
        body = ','.join('{%d,%d,%d,%d,%d,%d}' % e for e in entries)
        lines.append(f'static const r6_row r6_rows_{pid}[{len(entries)}] = {{{body}}};  /* {name}.C */')
        lines.append(f'static const uint8_t r6_wrttbl_{pid}[49] = {{{",".join(map(str, wrttbl(name)))}}};')
        meta.append(f'{{"{name}",{len(entries)},r6_rows_{pid},r6_wrttbl_{pid}}}')
    lines.append(f'static const r6_program r6_programs[12] = {{{",".join(meta)}}};')
    return '\n'.join(lines)+'\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    text = build()
    if args.check:
        if OUT.read_text() != text:
            sys.exit(f'FAIL: {OUT.relative_to(ROOT)} is stale; run tools/background_r6_assets.py')
        print(f'PASS: {OUT.relative_to(ROOT)} matches tools/scroll/R6/draft')
        return
    OUT.write_text(text)
    print('wrote', OUT.relative_to(ROOT))


if __name__ == '__main__':
    main()

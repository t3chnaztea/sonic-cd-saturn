#!/usr/bin/env python3
"""Extract Wacky Workbench COL6A-D palette scripts into src/background_r6_palette.inc.

    python3 tools/ww_palette_assets.py           write the include
    python3 tools/ww_palette_assets.py --check   fail if the include is stale

Each COL6x.C clchgctr() -> colchg6a/6b() runs four clchg_sub0(&clchgtim[i],
&clchgcnt[i], col6a<i>cnt, col6a<i>col) scripts every update; script 3 is the
flashing floor (entry 49).  COL6C/COL6D (Act 3) swap script 3's colors for
col6a3col_stop while bossflag & 32.  Every script and color table must appear
byte-identical in each retail MMD that links it (R6<act><era>).
"""
import argparse
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tools'))
from convert_assets import palette  # noqa: E402
from extract_mmd import disc_files  # noqa: E402
from tt_palette_assets import entries  # noqa: E402

SOURCE = ROOT/'build/audit/source/src/R6'
OUT = ROOT/'src/background_r6_palette.inc'
CALL = re.compile(r'clchg_sub0\(&clchgtim\[(\d)\], &clchgcnt\[(\d)\], (\w+), (\w+)\)')
MMDS = {'A': ['R61A', 'R62A'], 'B': ['R61B', 'R62B'], 'C': ['R61C', 'R62C', 'R63C'], 'D': ['R61D', 'R62D', 'R63D']}


def build():
    files = disc_files((ROOT/'build/retail/sonic.iso').read_bytes())
    out = ['/* Generated by tools/ww_palette_assets.py from COL6A-D.C, cross-checked in the retail MMDs.  Do not edit. */']
    proofs = 0
    eras = []
    for letter in 'ABCD':
        src = (SOURCE/f'COL6{letter}.C').read_text()
        fn = re.search(r'void colchg6[ab]\(void\) \{(.*?)\n\}', src, re.S)[1]
        calls = CALL.findall(fn)
        stop = letter in 'CD'
        assert [(int(a), int(b)) for a, b, _, _ in calls] == [(i, i) for i in range(3)]+[(3, 3)]*(2 if stop else 1), (letter, calls)
        if stop:
            assert re.search(r'if \(!\(bossflag & 32\)\)', fn) and calls[4][3] == 'col6a3col_stop', letter
        names = []
        for n, (_, _, cnt, col) in enumerate(calls):
            table = bytes(int(v) for v in re.findall(r'\d+', re.search(r'unsigned char '+cnt+r'\[\d+\] = \{(.*?)\};', src, re.S)[1]))
            colors = entries(src, col)
            assert len(table) == table[1]*2+2, cnt
            for m in MMDS[letter]:
                mmd = files[m+'__.MMD']
                assert table in mmd and colors in mmd, (m, cnt, col)
                proofs += 2
            words = struct.unpack(f'>{len(colors)//2}H', palette(colors))
            if n < 4:
                out.append(f'static const uint8_t r6_{letter}_{cnt}[{len(table)}] = {{{",".join(map(str, table))}}};')
            out.append(f'static const uint16_t r6_{letter}_{col}[{len(words)}] = {{{",".join(map(str, words))}}};')
            names.append((f'r6_{letter}_{cnt}', f'r6_{letter}_{col}'))
        stop_colors = names[4][1] if stop else '0'
        eras.append('{{'+','.join(f'{{{c},{d}}}' for c, d in names[:4])+f'}},{stop_colors}}}')
    out.append('typedef struct { const uint8_t *script; const uint16_t *colors; } r6_pal_call;')
    out.append('typedef struct { r6_pal_call call[4]; const uint16_t *stop; } r6_pal_set;')
    out.append('/* [era]: COL6A-D; stop = script 3 colors while bossflag & 32 (Act 3 only). */')
    out.append('static const r6_pal_set r6_pal_sets[4] = {'+','.join(eras)+'};')
    return '\n'.join(out)+'\n', proofs


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    text, proofs = build()
    if args.check:
        if OUT.read_text() != text:
            sys.exit(f'FAIL: {OUT.relative_to(ROOT)} is stale')
        print(f'PASS: {OUT.relative_to(ROOT)} current; {proofs} script/color tables found in retail MMDs')
        return
    OUT.write_text(text)
    print('wrote', OUT.relative_to(ROOT), f'({proofs} retail table matches)')


if __name__ == '__main__':
    main()

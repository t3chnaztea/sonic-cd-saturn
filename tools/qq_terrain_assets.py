#!/usr/bin/env python3
"""Quartz Quadrant runtime background art and enkeino maps -> assets/generated/qq_terrain.inc.

    python3 tools/qq_terrain_assets.py           capture retail art, write the include
    python3 tools/qq_terrain_assets.py --check   re-capture and fail if the include differs

The harvested packs hold each program's Nemesis level art and its level-start
background layout.  At run time the original replaces background art: enkeichg
(SCR51A-52D.C) calls ChangeTileBmp over a tile run for each enkeino band
(bitmaps, not in the Nemesis art) and mapset2 writes zonemaptbl[2]'s blocks
into the background layout; SCR53C also shows tile 688, past its Nemesis art.
The PC source names bitmap numbers, not art, so the art is read from the
original: each program runs from its start, the player walks into and is held in
the enkeino 0 band (and, in Acts 1-2, the enkeino 1 band) until the camera
settles, and VRAM and levelLayout are recorded.  Kept per program and band:
every tile the background layout references (through the pack's chunks and
blocks) whose retail VRAM art differs from the pack, or that lies past the
pack's art, as one contiguous run; and the background layout cells that differ
between the bands.  The pack's layout must equal retail levelLayout in the
enkeino 0 band.  Art is retail data: this writes under assets/generated only.
"""
import argparse
import hashlib
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tools'))
OUT = ROOT/'assets/generated/qq_terrain.inc'
PROGRAMS = {0: '1A', 1: '1B', 2: '1C', 3: '1D', 4: '2A', 5: '2B', 6: '2C', 7: '2D', 10: '3C', 11: '3D'}
# Camera X held in each band (player X = camera X + 160); enkeichg bands are
# player X <= 3584, <= 8960 (Act 2: 7168), above.
BANDS = {1: (1000, 5000), 2: (1000, 5000), 3: (1500, None)}


def parts(pack):
    return [pack[o:o+n] for o, n in (struct.unpack_from('>II', pack, 4+8*i) for i in range(6))]


def referenced(p, layout, table=None):
    """Tile indices the background layout (8 rows x 64 chunk ids) references;
    `table` is the program's full chunk table (the pack holds a prefix)."""
    chunks = table or p[2]
    tiles = set()
    for c in {v & 127 for v in layout}:
        if not c or c*512 > len(chunks):
            continue
        for e in range(256):
            b = struct.unpack_from('>H', chunks, (c-1)*512+e*2)[0] & 1023
            if b*8+8 <= len(p[1]):
                for k in range(4):
                    tiles.add(struct.unpack_from('>H', p[1], b*8+k*2)[0] & 2047)
    return tiles


def capture(pid):
    from capture_cc_scroll import boot
    from capture_r5_scroll import settle
    from capture_cc_plane import walk
    act, era = int(PROGRAMS[pid][0]), PROGRAMS[pid][1]
    core, e, frame, program = boot(era, act, 5)
    shots = []
    for x in BANDS[act]:
        if x is None:
            continue
        # Walk there as in play (a jump into a band can skip SCR52B's tile
        # swap), then hold twice: the second hold proves the art is steady.
        frame = walk(core, e, frame, x, 300)
        settle(core, e, x, 300, 90)
        a = (core.swapped(core.vram, 0, 0x10000), core.work_read(e['levelLayout'], 0x800))
        settle(core, e, x, 300, 30)
        b = (core.swapped(core.vram, 0, 0x10000), core.work_read(e['levelLayout'], 0x800))
        assert a[1] == b[1], (pid, x, 'layout not steady')
        shots.append((b[0], bytes(b[1][r*128+64+c] for r in range(8) for c in range(64)), a[0]))
    return shots, hashlib.sha256(program).hexdigest(), core.work_read(0xff0000, 0x10000)


MMDS = None


def build():
    global MMDS
    from extract_mmd import disc_files
    MMDS = disc_files((ROOT/'build/retail/sonic.iso').read_bytes())
    out = ['/* Generated by tools/qq_terrain_assets.py from the original R5 programs (retail art).  Do not edit. */']
    rows = []
    for pid, name in PROGRAMS.items():
        pack = (ROOT/f'assets/generated/qq5{name}.bin').read_bytes()
        p = parts(pack)
        count = len(p[0])//32
        shots, sha, ram = capture(pid)
        base = shots[0][1]
        assert base == p[4], (name, 'pack background layout differs from retail levelLayout')
        mmd = MMDS[f'R5{name}__.MMD']
        table = mmd.find(p[2][:2048])
        assert table >= 0 and mmd[table:table+len(p[2])] == p[2], name
        full = mmd[table:table+128*512]
        runs, cells = [], []
        for band, (vram, layout, first) in enumerate(shots):
            refs = referenced(p, layout, full)
            if band:
                refs |= referenced(p, base)
            changed = sorted(t for t in refs if t >= count or vram[t*32:t*32+32] != p[0][t*32:t*32+32])
            runs.append((changed, vram, first))
            if band:
                cells = [(i//64, i % 64, base[i], layout[i]) for i in range(512) if layout[i] != base[i]]
        lo = min((c[0][0] for c in runs if c[0]), default=0)
        hi = max((c[0][-1] for c in runs if c[0]), default=-1)
        n = hi-lo+1 if hi >= lo else 0
        arts = []
        # Past the Nemesis art only referenced tiles are background art (the
        # run stays below the VDP2 maps at 0x10000).
        assert all(any(t in c[0] for c in runs) for t in range(count, hi+1)) and (hi+1)*32 <= 0x10000, (name, lo, hi, count)
        for band, (changed, vram, first) in enumerate(runs):
            if not n:
                break
            art = vram[lo*32:(hi+1)*32]
            # Art still changing between the two holds would not be steady
            # background art (object art sharing the cells).
            assert art == first[lo*32:(hi+1)*32], (name, band, 'art not steady')
            out.append(f'static const uint8_t qq_art_{pid}_{band}[{n*32}] = {{{",".join(map(str, art))}}};')
            arts.append(f'qq_art_{pid}_{band}')
        while len(arts) < 2:
            arts.append(arts[0] if arts else '0')
        # Chunks past the pack's table: the original's chunk (the MMD holds the
        # table the pack is a prefix of) is written over the chunk it replaces
        # while enkeino is odd, so that cell keeps its layout value.  The host
        # must not appear in the foreground layout, and elsewhere in the
        # background layout only in columns >= 2, which the all-static
        # enkeino 1 rows (x 0..511) never show.
        chunks = {}
        for r, c, v0, v1 in cells:
            if v1*512 > len(p[2]):
                assert chunks.get(v0, v1) == v1 and not any(v & 127 == v0 for v in p[3]), (name, r, c)
                assert all(i % 64 >= 2 for i, v in enumerate(p[4]) if v & 127 == v0 and (i//64, i % 64) not in
                           [(rr, cc) for rr, cc, vv, _ in cells if vv == v0]), (name, v0)
                alt = mmd[table+(v1-1)*512:table+v1*512]
                # A block past the pack's table: native's bound reads tile 0,
                # so retail RAM past its block table must hold zero words there.
                at = ram.find(p[1][:256])
                assert at >= 0 and ram[at:at+len(p[1])] == p[1], name
                for k in range(256):
                    blk = struct.unpack_from('>H', alt, k*2)[0] & 1023
                    if blk >= len(p[1])//8:
                        assert ram[at+blk*8:at+blk*8+8] == bytes(8), (name, v1, blk)
                chunks[v0] = v1
        for host, v1 in sorted(chunks.items()):
            out.append(f'static const uint8_t qq_chunk_{pid}_{host}[512] = {{{",".join(map(str, mmd[table+(v1-1)*512:table+v1*512]))}}};')
            out.append(f'static const uint8_t qq_chunk_{pid}_{host}_0[512] = {{{",".join(map(str, p[2][(host-1)*512:host*512]))}}};')
        swaps = ','.join(f'{{{h},{{qq_chunk_{pid}_{h}_0,qq_chunk_{pid}_{h}}}}}' for h in sorted(chunks)) or '{0}'
        out.append(f'static const qq_chunk qq_chunks_{pid}[{max(len(chunks), 1)}] = {{{swaps}}};')
        cells = [cc for cc in cells if cc[3]*512 <= len(p[2])]
        cell_text = ','.join('{%d,%d,%d,%d}' % c for c in cells) or '{0}'
        out.append(f'static const qq_cell qq_cells_{pid}[{max(len(cells), 1)}] = {{{cell_text}}};')
        rows.append(f'{{{lo},{n},{max(count, hi+1)},{{{arts[0]},{arts[1]}}},{len(cells)},qq_cells_{pid},{len(chunks)},qq_chunks_{pid}}}  /* R5{name} {sha[:12]} */')
        print(f'R5{name}: art {lo}+{n} (enkeino 0: {len(runs[0][0])} tiles'
              + (f', enkeino 1: {len(runs[1][0])} tiles' if len(runs) > 1 else '') + f'), {len(cells)} layout cells, {len(chunks)} chunk swaps', flush=True)
    out.append('static const qq_terrain qq_terrain_programs[12] = {' + ','.join(
        rows[list(PROGRAMS).index(i)] if i in PROGRAMS else '{0}' for i in range(12)) + '};')
    return '\n'.join(out)+'\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    text = build()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f'FAIL: {OUT.relative_to(ROOT)} differs from a fresh retail capture')
        print(f'PASS: {OUT.relative_to(ROOT)} matches a fresh retail capture of 10 R5 programs')
        return
    OUT.write_text(text)
    print('wrote', OUT.relative_to(ROOT))


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Extract Tidal Tempest COL4A-D palette scripts into src/background_r4_palette.inc.

    python3 tools/tt_palette_assets.py           write the include
    python3 tools/tt_palette_assets.py --check   fail if the include is stale

Each clchgctr() in COL4A-D.C calls clchg_sub0(&clchgtim[i], &clchgcnt[i], cnt, col).
COL4A has two sets on shared timers: the Act 1 start area (camera X < 640, Y < 352)
and the rest (plus a one-shot colorset2(4) = zone4colora into entries 16-63 when
the camera first enters X < 640, Y >= 352).  COL4B-D cycle only outside Act 1.
Every script and color table must appear byte-identical in the retail MMDs that
link it (R41A for COL4A; R42x for COL4B-D), as tools/cc_palette_source.py.
"""
import argparse
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tools'))
from convert_assets import palette  # noqa: E402
from extract_mmd import disc_files  # noqa: E402

SOURCE = ROOT/'build/audit/source/src/R4'
OUT = ROOT/'src/background_r4_palette.inc'
CALL = re.compile(r'clchg_sub0\(&clchgtim\[(\d)\], &clchgcnt\[(\d)\], (\w+), (\w+)\)')


def entries(source, name):
    body = re.search(r'PALETTEENTRY '+name+r'\[\d+\] = \{(.*?)\};', source, re.S)[1]
    v = list(map(int, re.findall(r'\d+', body)))
    assert len(v) % 4 == 0 and all(x % 32 == 0 for i, x in enumerate(v) if i % 4 != 3), name
    return b''.join(struct.pack('>H', v[i]//16 | v[i+1]//16 << 4 | v[i+2]//16 << 8) for i in range(0, len(v), 4))


def build(check_retail=True):
    files = disc_files((ROOT/'build/retail/sonic.iso').read_bytes()) if check_retail else None
    out = ['/* Generated by tools/tt_palette_assets.py from COL4A-D.C, cross-checked in the retail MMDs.  Do not edit. */']
    sets = {}
    proofs = 0
    for letter in 'ABCD':
        path = SOURCE/f'COL4{letter}.C'
        src = path.read_text()
        fn = re.search(r'void clchgctr\(void\) \{(.*?)\n\}', src, re.S)[1]
        calls = [(int(a), c, d) for a, b, c, d in CALL.findall(fn) if a == b]
        assert len(calls) == len(CALL.findall(fn))
        mmd = files[f'R4{1 if letter == "A" else 2}{letter}__.MMD'] if files else None
        blocks = {}
        for i, cnt, col in calls:
            table = bytes(int(v) for v in re.findall(r'\d+', re.search(r'unsigned char '+cnt+r'\[\d+\] = \{(.*?)\};', src, re.S)[1]))
            colors = entries(src, col)
            assert len(table) == table[1]*2+2, cnt
            if mmd is not None:
                assert table in mmd and colors in mmd, (letter, cnt, col)
                proofs += 2
            words = struct.unpack(f'>{len(colors)//2}H', palette(colors))
            out.append(f'static const uint8_t r4_{cnt}[{len(table)}] = {{{",".join(map(str, table))}}};')
            if col not in blocks:
                blocks[col] = 1
                out.append(f'static const uint16_t r4_{col}[{len(words)}] = {{{",".join(map(str, words))}}};')
        if letter == 'A':
            # The first four calls follow label1 (the cave/other set); the six
            # after the else are the start-area set.  Timers are shared.
            assert [c[0] for c in calls] == [0, 1, 2, 3, 0, 1, 2, 3, 4, 5], calls
            assert re.search(r'scra_h_posit\.w\.h >= 640\) goto label1;.*?scra_v_posit\.w\.h >= 352\).*?clchgtim\[4\] & 128.*?colorset2\(4\);', fn, re.S)
            sets['A'] = (calls[:4], calls[4:])
            z = entries(src, 'zone4colora')
            if mmd is not None:
                assert z in mmd
                proofs += 1
            assert re.search(r'\{ zone4colora, 16, 48 \}', src)
            out.append(f'static const uint16_t r4_zone4colora[48] = {{{",".join(map(str, struct.unpack(">48H", palette(z))))}}};')
        else:
            assert re.search(r'if \(stageno\.b\.l\) \{', fn), letter
            sets[letter] = (calls, [])
    out.append('typedef struct { uint8_t timer; const uint8_t *script; const uint16_t *colors; } r4_pal_call;')
    names = {}
    for letter, (other, start) in sets.items():
        for tag, calls in (('other', other), ('start', start)):
            if calls:
                names[letter, tag] = f'r4_pal_{letter}_{tag}'
                out.append(f'static const r4_pal_call r4_pal_{letter}_{tag}[{len(calls)}] = {{'
                           + ','.join(f'{{{i},r4_{c},r4_{d}}}' for i, c, d in calls)+'};')
    out.append('/* [era]: calls outside the start area (Act 2/3; COL4A also Act 1 X >= 640 or Y >= 352), start-area calls. */')
    out.append('static const r4_pal_call *const r4_pal_other[4] = {'+','.join(names[l, 'other'] for l in 'ABCD')+'};')
    out.append('static const uint8_t r4_pal_other_count[4] = {'+','.join(str(len(sets[l][0])) for l in 'ABCD')+'};')
    out.append(f'static const r4_pal_call *const r4_pal_start = {names["A", "start"]};')
    out.append(f'static const uint8_t r4_pal_start_count = {len(sets["A"][1])};')
    return '\n'.join(out)+'\n', proofs


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    text, proofs = build()
    if args.check:
        if OUT.read_text() != text:
            sys.exit(f'FAIL: {OUT.relative_to(ROOT)} is stale')
        print(f'PASS: {OUT.relative_to(ROOT)} current; {proofs} script/color tables found in retail MMDs')
        return
    OUT.write_text(text)
    print('wrote', OUT.relative_to(ROOT), f'({proofs} retail table matches)')


if __name__ == '__main__':
    main()

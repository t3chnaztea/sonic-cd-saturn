#!/usr/bin/env python3
"""Write build/probe-source/camera_v_variants.inc (included by src/camera_v.c): the original vertical camera of every
round program, compiled verbatim.

Each SCR<round><act><era>.C carries scroll_v and its helpers (sv_move_main,
sv_move_main1, sv_move_main2, sv_move_sub2, sv_move_sub, sv_move_minus,
sv_move_plus, scrv_up_ch, scrv_down_ch, scrv_move). The seventy programs share
twelve distinct texts; each distinct text is emitted once with its functions
prefixed cv<n>_, and scd_camera_v_variant[round][act][era] names the text a
program uses (0xff: no such program). Programs whose SCR file is absent from
the source (R42B, R42D) use their act's Present text; tools/camera_retail.py
checks R42 against the retail disc.

--per-program also writes build/camera/camera_v_programs.c with one static,
unshared copy per program for the dedupe fixture (tools/test-camera.sh).
"""
import hashlib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from audit_source import ROOT, UPSTREAM
from water_original import functions, strip

NAMES = ['scroll_v', 'sv_move_main', 'sv_move_main1', 'sv_move_main2', 'sv_move_sub2', 'sv_move_sub',
         'sv_move_minus', 'sv_move_plus', 'scrv_up_ch', 'scrv_down_ch', 'scrv_move']
H_NAMES = ['scroll_h', 'scrh_move', 'right_check', 'left_check']
ROUNDS = [1, 3, 4, 5, 6, 7, 8]
HEADER = '#include "EQU.H"\n'


def family(path):
    fn = functions(strip(path.read_text()))
    bodies = {n: fn[n] for n in NAMES if n in fn}
    # Adaptation: sv_move_sub adds the step to the camera as a 68k word add. The
    # PC long add carries into the high word (the fraction after scrv_move's
    # word swap) when the step is negative; retail cameraY keeps fraction 0
    # (tools/camera_retail_test.c, R11A).
    if 'sv_move_sub' in bodies:
        bodies['sv_move_sub'] = bodies['sv_move_sub'].replace('lD1.l += scra_v_posit.w.h;', 'lD1.w.l += scra_v_posit.w.h;')
    # Retail scrv_down_ch (R43D__.MMD $3058: "subi.w #$800,d1; bcs.s") wraps
    # when the camera reaches the limit exactly (result 0); the PC decompile
    # tests > 0, which wraps one update late (retail TT3D level frame 1186).
    if 'scrv_down_ch' in bodies:
        bodies['scrv_down_ch'] = re.sub(r'(\w+)\.w\.l -= 2048;(\s*)if \(\1\.w\.l > 0\)', r'\1.w.l -= 2048;\2if (\1.w.l >= 0)',
                                        bodies['scrv_down_ch'])
    return bodies


def rename(bodies, prefix, static=False, names=NAMES):
    text = []
    for n in names:
        if n not in bodies:
            continue
        body = re.sub(r'^\s*static\s+', '', bodies[n])
        for m in names:
            body = re.sub(r'\b' + m + r'\b', prefix + m, body)
        text.append(('static ' if static else '') + body)
    protos = [('static ' if static else '') + re.match(r'[^{]*', re.sub(r'^\s*static\s+', '', bodies[n]).replace(n, prefix + n, 1))[0].strip() + ';'
              for n in names if n in bodies]
    return '\n'.join(protos) + '\n' + '\n'.join(text)


def programs():
    src = UPSTREAM/'src'
    for r in ROUNDS:
        for act in range(3):
            for era in range(4):
                if act == 2 and era < 2:
                    continue
                name = f'R{r}{act+1}{"ABCD"[era]}'
                path = src/f'R{r}/SCR{r}{act+1}{"ABCD"[era]}.C'
                fallback = None
                if not path.exists():
                    fallback = src/f'R{r}/SCR{r}{act+1}{"A" if act < 2 else "C"}.C'
                yield r, act, era, name, path if path.exists() else fallback, fallback is not None


def main():
    variants, keys, table, notes = [], {}, {}, []
    per_program = []
    for r, act, era, name, path, fell_back in programs():
        bodies = family(path)
        if 'scroll_v' not in bodies:
            raise ValueError(f'{path}: no scroll_v')
        key = hashlib.sha256('\n'.join(re.sub(r'\s+', '', bodies.get(n, '')) for n in NAMES).encode()).hexdigest()
        if key not in keys:
            keys[key] = len(variants)
            variants.append((path, bodies))
        table[(ROUNDS.index(r), act, era)] = keys[key]
        if fell_back:
            notes.append(f'{name} uses {path.name}')
        per_program.append((name, ROUNDS.index(r), act, era, bodies))
    out = ['/* Generated by tools/camera_source.py. Do not edit. Included by src/camera_v.c after EQU.H. */']
    for i, (path, bodies) in enumerate(variants):
        out.append(f'/* variant {i}: {path.parent.name}/{path.name} */')
        out.append(rename(bodies, f'cv{i}_'))
    out.append('void (*const scd_camera_v_variants[%d])(void)={%s};' %
               (len(variants), ','.join(f'cv{i}_scroll_v' for i in range(len(variants)))))
    rows = []
    for ri in range(len(ROUNDS)):
        acts = []
        for act in range(3):
            acts.append('{' + ','.join(str(table.get((ri, act, era), 255)) for era in range(4)) + '}')
        rows.append('{' + ','.join(acts) + '}')
    out.append('const unsigned char scd_camera_v_variant[7][3][4]={' + ','.join(rows) + '};')
    out.append('/* ' + '; '.join(notes) + ' */')
    # Horizontal camera (scroll() runs scroll_h before scroll_v): same programs,
    # texts deduplicated the same way, functions prefixed ch<n>_.
    hvariants, hkeys, htable, hper = [], {}, {}, []
    for r, act, era, name, path, fell_back in programs():
        fn = functions(strip(path.read_text()))
        bodies = {n: fn[n] for n in H_NAMES if n in fn}
        if 'scroll_h' not in bodies or 'scrh_move' not in bodies:
            raise ValueError(f'{path}: no scroll_h')
        key = hashlib.sha256('\n'.join(re.sub(r'\s+', '', re.sub(r'^\s*static\s+', '', bodies.get(n, ''))) for n in H_NAMES).encode()).hexdigest()
        if key not in hkeys:
            hkeys[key] = len(hvariants)
            hvariants.append((path, bodies))
        htable[(ROUNDS.index(r), act, era)] = hkeys[key]
        hper.append((name, ROUNDS.index(r), act, era, bodies))
    for i, (path, bodies) in enumerate(hvariants):
        out.append(f'/* horizontal variant {i}: {path.parent.name}/{path.name} */')
        out.append(rename(bodies, f'ch{i}_', static=True, names=H_NAMES))
    out.append('static void (*const scd_camera_h_variants[%d])(void)={%s};' %
               (len(hvariants), ','.join(f'ch{i}_scroll_h' for i in range(len(hvariants)))))
    rows = []
    for ri in range(len(ROUNDS)):
        rows.append('{' + ','.join('{' + ','.join(str(htable.get((ri, act, era), 255)) for era in range(4)) + '}'
                                   for act in range(3)) + '}')
    out.append('static const unsigned char scd_camera_h_variant[7][3][4]={' + ','.join(rows) + '};')
    # PLAYER.C scr_h (first in play00move) moves the centre scroll_h follows.
    out.append('/* PLAYER.C scr_h */')
    out.append(functions(strip((UPSTREAM/'src/PLAYER.C').read_text()))['scr_h'])
    path = ROOT/'build/probe-source/camera_v_variants.inc'
    path.parent.mkdir(parents=True, exist_ok=True)
    text = '\n'.join(out) + '\n'
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
    if '--per-program' in sys.argv:
        pp = [HEADER]
        for k, (name, ri, act, era, bodies) in enumerate(per_program):
            pp.append(f'/* {name} */')
            pp.append(rename(bodies, f'pp{k}_', static=True))
        pp.append('void (*const camera_v_programs[%d])(void)={%s};' %
                  (len(per_program), ','.join(f'pp{k}_scroll_v' for k in range(len(per_program)))))
        pp.append('const unsigned char camera_v_program_key[%d][3]={%s};' %
                  (len(per_program), ','.join('{%d,%d,%d}' % (ri, act, era) for _, ri, act, era, _ in per_program)))
        out_dir = ROOT/'build/camera'
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir/'camera_v_programs.c').write_text('\n'.join(pp) + '\n')
        hp = [HEADER]
        for k, (name, ri, act, era, bodies) in enumerate(hper):
            hp.append(f'/* {name} */')
            hp.append(rename(bodies, f'hp{k}_', static=True, names=H_NAMES))
        hp.append('void (*const camera_h_programs[%d])(void)={%s};' %
                  (len(hper), ','.join(f'hp{k}_scroll_h' for k in range(len(hper)))))
        hp.append('const unsigned char camera_h_program_key[%d][3]={%s};' %
                  (len(hper), ','.join('{%d,%d,%d}' % (ri, act, era) for _, ri, act, era, _ in hper)))
        (out_dir/'camera_h_programs.c').write_text('\n'.join(hp) + '\n')
    print(f'camera_v_variants.inc: {len(per_program)} programs, {len(variants)} vertical and {len(hvariants)} horizontal variants; ' + '; '.join(notes))


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Generate src/scroll_limits.h from the retail per-act scroll programs.

Every retail stage program SCR<round><act><era>.C opens with two initialised
tables that the port had previously hand-copied for Palmtree Panic only:

    scr_dir_tbl[6]   = { scrar_no, left, right, up, down, vline }
    playmapnotbl[4]  = { loopmapno, loopmapno2, ballmapno, ballmapno2 }

Sixty-eight of the seventy programs have C sources in build/audit/source.
R42B and R42D do not, so their tables are recovered from the disc images by
matching the twelve-byte scr_dir_tbl initialiser.  The same match is run over
all sixty-eight programs that *do* have sources and must agree with the C
tables exactly, so the recovery is proven before it is trusted.
"""
import json,os,re,struct,sys
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0,os.path.join(ROOT,'tools'))
SOURCE=os.path.join(ROOT,'build/audit/source/src')
# GAME.C indexes da_tbl[7][...] by stageno.b.h over the seven playable rounds.
ROUNDS=[1,3,4,5,6,7,8]
ERAS='ABCD'
ZONE_NAMES=['PALMTREE PANIC','COLLISION CHAOS','TIDAL TEMPEST','QUARTZ QUADRANT',
            'WACKY WORKBENCH','STARDUST SPEEDWAY','METALLIC MADNESS']

def c_table(text,name,count):
    match=re.search(re.escape(name)+r'\['+str(count)+r'\]\s*=\s*\{(.*?)\}',text,re.S)
    if not match:return None
    body=re.sub(r'/\*.*?\*/','',match.group(1),flags=re.S)
    values=[int(v) for v in re.findall(r'-?\d+',body)]
    return values if len(values)==count else None

def from_sources():
    out={}
    for round_no in ROUNDS:
        folder=os.path.join(SOURCE,f'R{round_no}')
        for act in (1,2,3):
            for era in ERAS:
                path=os.path.join(folder,f'SCR{round_no}{act}{era}.C')
                if not os.path.exists(path):continue
                text=open(path,errors='replace').read()
                scroll=c_table(text,'scr_dir_tbl',6)
                maps=c_table(text,'playmapnotbl',4)
                if scroll is None or maps is None:
                    raise ValueError(f'{path}: tables not in the expected form')
                out[f'R{round_no}{act}{era}']=(scroll,maps)
    return out

# scr_dir_tbl as the compiler lays it down: scrar_no is 4 and left is 0 in all
# seventy programs, vline is 96, so the six words pin down to one search.
BINARY=re.compile(rb'\x00\x04\x00\x00(..)(..)(..)\x00\x60',re.S)

def from_disc():
    from extract_zone import disc_files,read_iso
    disc=disc_files(read_iso())
    out={}
    for name,data in disc.items():
        key=re.fullmatch(r'(R[1-8][1-3][A-D])__\.MMD',name)
        if not key:continue
        hits={struct.unpack('>HHH',m.group(0)[4:10]) for m in BINARY.finditer(data) if not m.start()%2}
        if len(hits)==1:out[key.group(1)]=hits.pop()
    return out

def main():
    sources=from_sources()
    disc=from_disc()
    checked=0
    for key,(scroll,_) in sources.items():
        found=disc.get(key)
        if found is None:
            raise ValueError(f'{key}: no unique scr_dir_tbl in the disc image')
        if found!=(scroll[2],scroll[3],scroll[4]):
            raise ValueError(f'{key}: disc {found} disagrees with the C source {scroll[2:5]}')
        checked+=1
    recovered=sorted(set(disc)-set(sources))
    for key in recovered:
        right,up,down=disc[key]
        # No C source for these two.  Both Quartz Quadrant Act 2 programs that
        # do have sources carry an all-127 playmapnotbl, as does every other
        # Quartz Quadrant program, so the neutral row is not a guess about them.
        sources[key]=([4,0,right,up,down,96],[127,127,127,127])
    rows=[]
    for round_no in ROUNDS:
        for act in (1,2,3):
            for era_index,era in enumerate(ERAS):
                entry=sources.get(f'R{round_no}{act}{era}')
                if entry is None:
                    rows.append(None)
                    continue
                scroll,maps=entry
                rows.append((round_no,act,era,scroll,maps))
    header=[
        '/* Generated by tools/extract_scroll_limits.py.  Do not edit.',
        f'   {checked} of {len(sources)} rows verified against build/audit/source;',
        f'   {len(recovered)} recovered from the disc: {", ".join(recovered) or "none"}. */',
        '#ifndef SCROLL_LIMITS_H',
        '#define SCROLL_LIMITS_H',
        'typedef struct {',
        '    short right,up,down,vline;',
        '    unsigned char loopmapno,loopmapno2,ballmapno,ballmapno2;',
        '    unsigned char valid;',
        '} scroll_limits_t;',
        '/* [round][act][era]; round is stageno.b.h over R1,R3,R4,R5,R6,R7,R8.',
        '   Act 3 exists only in Good Future and Bad Future, so its Present and',
        '   Past rows are absent and carry valid = 0. */',
        'static const scroll_limits_t scroll_limits[7][3][4]={',
    ]
    index=0
    for round_no in ROUNDS:
        header.append(f'  {{ /* R{round_no} {ZONE_NAMES[ROUNDS.index(round_no)]} */')
        for act in (1,2,3):
            cells=[]
            for era in ERAS:
                row=rows[index];index+=1
                if row is None:
                    cells.append('{0,0,0,0,0,0,0,0,0}')
                    continue
                _,_,_,scroll,maps=row
                cells.append('{%d,%d,%d,%d,%d,%d,%d,%d,1}'%(
                    scroll[2],scroll[3],scroll[4],scroll[5],maps[0],maps[1],maps[2],maps[3]))
            header.append(f'    {{{",".join(cells)}}}, /* act {act} */')
        header.append('  },')
    header+=['};','#endif','']
    out=os.path.join(ROOT,'src/scroll_limits.h')
    open(out,'w').write('\n'.join(header))
    print(f'{out}: {checked} verified, {len(recovered)} recovered ({", ".join(recovered) or "none"})')
    if '--json' in sys.argv:
        print(json.dumps({k:v for k,v in sorted(sources.items())},indent=1))

if __name__=='__main__':
    main()

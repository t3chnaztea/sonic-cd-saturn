#!/usr/bin/env python3
"""Generate assets/generated/water_data.h for src/water.c (Tidal Tempest water).

Sources (all private, never committed):
- R4/WTBL41A..43.C watercolitbl current boxes. The upstream Makefile links
  WTBL4xC into both futures of an act (R41D/R42D use WTBL41C/WTBL42C).
- R4/GAME4.C waterpositbl, TBL0.C awasintbl, R4/PLAYSUB4.C plawachg,
  TBL1.C exit2chg.
- The water palette: PaletteTable entry 1 of every Tidal Tempest MMD, the
  64-colour set LoadWaterPal copies to waterPalette. Entries 0 and 1 are the
  same set in all ten programs; tools/water_retail.py checks it against the
  live retail waterPalette buffer.
"""
import re
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from audit_source import ROOT, UPSTREAM
from convert_assets import palette
from extract_mmd import disc_files
from extract_zone_auto import palette_table, ORIGIN

SRC = UPSTREAM/'src'
TABLES = ['41A', '41B', '41C', '42A', '42B', '42C', '43']
ERAS = 'ABCD'


def numbers(text):
    return [int(v) for v in re.findall(r'-?\d+', text)]


def array(source, name):
    body = re.search(name + r'\[\d*\]\s*=\s*\{(.*?)\};', re.sub(r'/\*.*?\*/', '', source, flags=re.S), re.S)
    if not body:
        raise ValueError(name)
    return numbers(body[1])


def table_for(act, era):
    if act == 2:
        return TABLES.index('43')
    return TABLES.index(f'4{act+1}{ERAS[min(era, 2)]}')


def main():
    out = []
    emit = out.append
    emit('/* Generated by tools/water_assets.py. Do not edit. */')
    emit('#ifndef WATER_DATA_H\n#define WATER_DATA_H\n#include <stdint.h>')
    sizes = []
    for name in TABLES:
        values = array((SRC/f'R4/WTBL{name}.C').read_text(), 'watercolitbl')
        # watercoli walks seven-word records until a negative left edge.
        end = next(i for i in range(0, len(values), 7) if values[i] < 0)
        values = values[:end + 1]
        sizes.append(len(values))
        emit(f'static const int16_t water_coli_{name}[{len(values)}]={{{",".join(map(str, values))}}};')
    emit('static const int16_t *const water_coli_tables[7]={' + ','.join(f'water_coli_{n}' for n in TABLES) + '};')
    emit('/* [act][era] -> water_coli_tables index (futures share the C table). */')
    emit('static const uint8_t water_coli_index[3][4]={' + ','.join(
        '{' + ','.join(str(table_for(a, e)) for e in range(4)) + '}' for a in range(3)) + '};')
    game4 = (SRC/'R4/GAME4.C').read_text()
    positions = array(game4, 'waterpositbl')
    assert len(positions) == 12
    emit(f'static const uint16_t water_position_table[12]={{{",".join(map(str, positions))}}};')
    awasin = array((SRC/'TBL0.C').read_text(), 'awasintbl')
    assert len(awasin) == 256
    emit(f'static const int8_t water_awasintbl[256]={{{",".join(str(v - 256 if v > 127 else v) for v in awasin)}}};')
    playsub = re.sub(r'/\*.*?\*/', '', (SRC/'R4/PLAYSUB4.C').read_text(), flags=re.S)
    scripts = []
    for i in range(15):
        scripts.append(array(playsub, f'plawachg{i}'))
    names = re.search(r'unsigned char\* plawachg\[16\] = \{(.*?)\}', playsub, re.S)[1]
    order = [int(n) for n in re.findall(r'plawachg(\d+)', names)]
    assert len(order) == 16
    for i, s in enumerate(scripts):
        emit(f'static const uint8_t water_plawachg{i}[{len(s)}]={{{",".join(map(str, s))}}};')
    emit('static const uint8_t *const water_plawachg[16]={' + ','.join(f'water_plawachg{i}' for i in order) + '};')
    tbl1 = re.sub(r'/\*.*?\*/', '', (SRC/'TBL1.C').read_text(), flags=re.S)
    exit_names = re.search(r'unsigned char\* exit2chg\[3\] = \{(.*?)\}', tbl1, re.S)[1]
    exit_scripts = re.findall(r'exit2chg(\d+)', exit_names)
    for n in sorted(set(exit_scripts)):
        s = array(tbl1, f'exit2chg{n}')
        emit(f'static const uint8_t water_exit2chg{n}[{len(s)}]={{{",".join(map(str, s))}}};')
    emit('static const uint8_t *const water_exit2chg[3]={' + ','.join(f'water_exit2chg{n}' for n in exit_scripts) + '};')
    # Water palettes from the retail programs.
    files = disc_files((ROOT/'build/retail/sonic.iso').read_bytes())
    sets = {}
    for act in range(3):
        for era in range(4):
            if act == 2 and era < 2:
                continue
            name = f'R4{act+1}{ERAS[era]}__.MMD'
            data = files[name]
            table = palette_table(data) - ORIGIN
            entries = [struct.unpack_from('>IHH', data, table + i * 8) for i in range(2)]
            assert entries[0] == entries[1], name
            pointer, buffer, longs = entries[1]
            assert buffer == 0xfb00 and longs == 31, name
            raw = data[pointer - ORIGIN:pointer - ORIGIN + 128]
            sets.setdefault(era, raw)
            assert sets[era] == raw, f'{name}: water palette differs between acts'
    emit('/* Saturn RGB1555 water palettes by era (0 Present, 1 Past, 2 Good, 3 Bad Future). */')
    emit('static const uint16_t water_palettes[4][64]={')
    for era in range(4):
        converted = palette(sets[era])
        words = struct.unpack('>64H', converted)
        emit('{' + ','.join(f'0x{w:04X}' for w in words) + '},')
    emit('};')
    emit('/* Mega Drive words of the same sets, for fixtures. */')
    emit('static const uint16_t water_palettes_md[4][64]={')
    for era in range(4):
        emit('{' + ','.join(f'0x{w:03X}' for w in struct.unpack('>64H', sets[era])) + '},')
    emit('};')
    emit('#endif')
    path = ROOT/'assets/generated/water_data.h'
    text = '\n'.join(out) + '\n'
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
    print(f'water_data.h: {len(TABLES)} current tables ({sum(sizes)} words), 4 water palettes')


if __name__ == '__main__':
    main()
